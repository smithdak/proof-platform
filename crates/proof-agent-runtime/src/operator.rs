        fixture
            .store
            .push_response(RecordingOperatorResponse::BudgetReserve(
                reservation_result(&fixture, &call, &lease),
            ));
        fixture
            .store
            .push_response(RecordingOperatorResponse::Dispatch(dispatch_result(
                &fixture, &call, &lease,
            )));
