/// The exact durable boundary at which a governed runtime operation failed.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OperatorRuntimeStage {
    Environment,
    ReplayLookup,
    ClaimLease,
    RenewLease,
    ReleaseLease,
    ReclaimLease,
    ReserveBudget,
    SettleBudget,
    BeginDispatch,
    ExecuteBoundary,
    SettleFailure,
    CommitResult,
}

#[derive(Debug, Error)]
pub enum OperatorRuntimeError {
    #[error("operator runtime environment failed: {0}")]
    Environment(#[from] OperatorEnvironmentError),
    #[error("operator runtime store failed at {stage:?}: {source}")]
    Store {
        stage: OperatorRuntimeStage,
        source: OperatorStoreError,
    },
    #[error("operator runtime contract failed at {stage:?}: {message}")]
    Contract {
        stage: OperatorRuntimeStage,
        message: String,
    },
    #[error("governed boundary failed and its dispatch was forfeited: {error}")]
    ExecutionSettled {
        error: ExecutionError,
        settlement: RuntimeFailureResult,
    },
    #[error("governed replay was rejected at begin_dispatch: {0:?}")]
    ReplayRejected(DispatchOutcome),
}

impl OperatorRuntimeError {
    fn store(stage: OperatorRuntimeStage, source: OperatorStoreError) -> Self {
        Self::Store { stage, source }
    }

    fn contract(stage: OperatorRuntimeStage, message: impl Into<String>) -> Self {
        Self::Contract {
            stage,
            message: message.into(),
        }
    }
}

/// Non-secret coordinates for a first lease claim. IDs and raw custody are
/// generated by the injected kernel environment inside [`OperatorRuntime`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OperatorLeaseClaim {
    pub workspace_id: Uuid,
    pub run_id: Uuid,
    pub owner_instance_id: Uuid,
    pub process_epoch_id: Uuid,
    pub expected_fence_epoch: u64,
    pub expected_control_revision: u64,
}

/// Non-secret coordinates for a fenced recovery attempt.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OperatorLeaseReclaim {
    pub workspace_id: Uuid,
    pub run_id: Uuid,
    pub expired_lease_id: Uuid,
    pub expected_fence_epoch: u64,
    pub expected_control_revision: u64,
    pub owner_instance_id: Uuid,
    pub new_process_epoch_id: Uuid,
    pub checkpoint: AgentCheckpointTail,
}

/// Sole process-local ownership of a raw lease token and its liveness guard.
/// This type deliberately exposes neither token bytes nor cloning/serialization.
pub struct OperatorLease {
    custody: LeaseTokenCustody,
    live: AtomicBool,
    control_revision: u64,
    lease: proof_kernel::RunLease,
}

impl OperatorLease {
    pub fn lease(&self) -> &proof_kernel::RunLease {
        &self.lease
    }

    pub fn control_revision(&self) -> u64 {
        self.control_revision
    }

    pub fn is_live(&self) -> bool {
        self.live.load(Ordering::Acquire)
    }

    /// Invalidates the process-local pre-entry guard. Durable barriers remain
    /// authoritative and independently reject stale fences and cancellations.
    pub fn invalidate_local_authority(&self) {
        self.live.store(false, Ordering::Release);
    }

    fn lose_authority_on(&self, error: OperatorStoreError) {
        if error == OperatorStoreError::StaleFence {
            self.invalidate_local_authority();
        }
    }
}

pub enum OperatorReclaimOutcome {
    Authority {
        lease: OperatorLease,
        outcome: ReclaimOutcome,
        directive: Option<RecoveryDirective>,
    },
    AmbiguousForfeited {
        control_revision: u64,
    },
}

/// Complete immutable input to one reserve/begin/execute/commit attempt.
pub struct GovernedRuntimeCall {
    pub intent: DispatchIntent,
    pub replay: Option<ReplayClaimBinding>,
    pub recovery: Option<RecoveryDirective>,
    pub input: Value,
    pub context: ExecutionContext,
    pub run_before: AgentRun,
    pub step_before: AgentRunStep,
    pub checkpoint: AgentCheckpointTail,
}

#[derive(Debug, Clone, PartialEq)]
pub enum GovernedRuntimeOutcome {
    Committed(RuntimeCommitResult),
    ExactReplay(ReplayCompletionBinding),
}

/// Storage-agnostic E0002 runtime coordinator. The store remains responsible
/// for every atomic CAS, budget account, command actionability check, and audit
/// append; this coordinator owns call ordering and one-use custody.
pub struct OperatorRuntime {
    engine: ExecutionEngine,
    store: Arc<dyn OperatorRuntimeStore>,
    environment: Arc<dyn OperatorControlEnvironment>,
}

impl OperatorRuntime {
    pub fn new(
        engine: ExecutionEngine,
        store: Arc<dyn OperatorRuntimeStore>,
        environment: Arc<dyn OperatorControlEnvironment>,
    ) -> Self {
        Self {
            engine,
            store,
            environment,
        }
    }

    pub fn claim_lease(
        &self,
        claim: OperatorLeaseClaim,
    ) -> Result<OperatorLease, OperatorRuntimeError> {
        let lease_id = self.environment.new_uuid_v7()?;
        let mut custody =
            LeaseTokenCustody::new(self.random_token(OperatorRandomPurpose::LeaseToken)?);
        let request = custody
            .claim_request(
                claim.workspace_id,
                claim.run_id,
                lease_id,
                claim.owner_instance_id,
                claim.process_epoch_id,
                claim.expected_fence_epoch,
                claim.expected_control_revision,
            )
            .map_err(|error| {
                OperatorRuntimeError::contract(OperatorRuntimeStage::ClaimLease, error.to_string())
            })?;
        let result = self.store.claim_run_lease(request).map_err(|error| {
            OperatorRuntimeError::store(OperatorRuntimeStage::ClaimLease, error)
        })?;
        custody.bind_claim_result(&result).map_err(|error| {
            OperatorRuntimeError::contract(OperatorRuntimeStage::ClaimLease, error.to_string())
        })?;
        Ok(OperatorLease {
            custody,
            live: AtomicBool::new(true),
            control_revision: result.control_revision,
            lease: result.lease,
        })
    }

    pub fn reclaim_lease(
        &self,
        reclaim: OperatorLeaseReclaim,
    ) -> Result<OperatorReclaimOutcome, OperatorRuntimeError> {
        let new_lease_id = self.environment.new_uuid_v7()?;
        let mut custody =
            LeaseTokenCustody::new(self.random_token(OperatorRandomPurpose::LeaseToken)?);
        let request = custody
            .reclaim_request(
                reclaim.workspace_id,
                reclaim.run_id,
                reclaim.expired_lease_id,
                reclaim.expected_fence_epoch,
                reclaim.expected_control_revision,
                new_lease_id,
                reclaim.owner_instance_id,
                reclaim.new_process_epoch_id,
                reclaim.checkpoint.checkpoint_id,
                u64::from(reclaim.checkpoint.sequence),
                reclaim.checkpoint.state_digest,
            )
            .map_err(|error| {
                OperatorRuntimeError::contract(
                    OperatorRuntimeStage::ReclaimLease,
                    error.to_string(),
                )
            })?;
        let result = self.store.reclaim_run(request).map_err(|error| {
            OperatorRuntimeError::store(OperatorRuntimeStage::ReclaimLease, error)
        })?;
        result.validate().map_err(|_| {
            OperatorRuntimeError::contract(
                OperatorRuntimeStage::ReclaimLease,
                "store returned an invalid reclaim result",
            )
        })?;
        if result.outcome == ReclaimOutcome::AmbiguousForfeited {
            return Ok(OperatorReclaimOutcome::AmbiguousForfeited {
                control_revision: result.control_revision,
            });
        }
        custody.bind_reclaim_result(&result).map_err(|error| {
            OperatorRuntimeError::contract(OperatorRuntimeStage::ReclaimLease, error.to_string())
        })?;
        let lease = result.lease.clone().ok_or_else(|| {
            OperatorRuntimeError::contract(
                OperatorRuntimeStage::ReclaimLease,
                "reclaim omitted acquired lease",
            )
        })?;
        Ok(OperatorReclaimOutcome::Authority {
            lease: OperatorLease {
                custody,
                live: AtomicBool::new(true),
                control_revision: result.control_revision,
                lease,
            },
            outcome: result.outcome,
            directive: result.directive,
        })
    }

    pub fn renew_lease(&self, lease: &mut OperatorLease) -> Result<(), OperatorRuntimeError> {
        let authority = lease
            .custody
            .authority(lease.control_revision)
            .map_err(|error| {
                OperatorRuntimeError::contract(OperatorRuntimeStage::RenewLease, error.to_string())
            })?;
        let request = LeaseRenewRequest {
            schema: "proof.operator.lease-renew-request/v1".into(),
            authority,
        };
        let result = match self.store.renew_run_lease(request) {
            Ok(result) => result,
            Err(error) => {
                lease.lose_authority_on(error);
                return Err(OperatorRuntimeError::store(
                    OperatorRuntimeStage::RenewLease,
                    error,
                ));
            }
        };
        self.accept_renewal(lease, result)
    }

    pub fn release_lease(
        &self,
        lease: OperatorLease,
    ) -> Result<LeaseMutationResult, OperatorRuntimeError> {
        lease.invalidate_local_authority();
        let expected = lease.control_revision;
        let request = lease
            .custody
            .into_release_request(expected)
            .map_err(|error| {
                OperatorRuntimeError::contract(
                    OperatorRuntimeStage::ReleaseLease,
                    error.to_string(),
                )
            })?;
        let result = self.store.release_run_lease(request).map_err(|error| {
            OperatorRuntimeError::store(OperatorRuntimeStage::ReleaseLease, error)
        })?;
        if result.validate().is_err() || result.outcome != LeaseMutationOutcome::Released {
            return Err(OperatorRuntimeError::contract(
                OperatorRuntimeStage::ReleaseLease,
                "store returned an invalid lease release",
            ));
        }
        Ok(result)
    }

    pub fn execute(
        &self,
        lease: &mut OperatorLease,
        call: GovernedRuntimeCall,
    ) -> Result<GovernedRuntimeOutcome, OperatorRuntimeError> {
        self.validate_call(lease, &call)?;
        if let Some(binding) = call.replay.as_ref() {
            if let Some(completion) = self.lookup_replay(binding)? {
                return Ok(GovernedRuntimeOutcome::ExactReplay(completion));
            }
        }
        if !lease.is_live() {
            return Err(OperatorRuntimeError::contract(
                OperatorRuntimeStage::ReserveBudget,
                "lease authority is no longer live",
            ));
        }

        let reservation_id = self.environment.new_uuid_v7()?;
        let idempotency_key = self.environment.new_uuid_v7()?;
        let intent_digest = control_digest_serialized(
            "Proof-Operator-Dispatch-Intent-v1",
            &call.intent,
        )
        .map_err(|error| {
            OperatorRuntimeError::contract(OperatorRuntimeStage::ReserveBudget, error.to_string())
        })?;
        let reserve = {
            let authority = lease
                .custody
                .authority(lease.control_revision)
                .map_err(|error| {
                    OperatorRuntimeError::contract(
                        OperatorRuntimeStage::ReserveBudget,
                        error.to_string(),
                    )
                })?;
            self.store.reserve_aggregate_budget(BudgetReserveRequest {
                schema: "proof.operator.budget-reserve-request/v1".into(),
                authority,
                reservation_id,
                idempotency_key,
                intent: call.intent.clone(),
                intent_digest,
                replay: call.replay.clone(),
                recovery: call.recovery.clone(),
            })
        };
        let reserve = match reserve {
            Ok(result) => result,
            Err(error) => {
                lease.lose_authority_on(error);
                if error == OperatorStoreError::NotActionable {
                    if let Some(binding) = call.replay.as_ref() {
                        if let Some(completion) = self.lookup_replay(binding)? {
                            return Ok(GovernedRuntimeOutcome::ExactReplay(completion));
                        }
                    }
                }
                return Err(OperatorRuntimeError::store(
                    OperatorRuntimeStage::ReserveBudget,
                    error,
                ));
            }
        };
        self.validate_reservation(
            lease,
            &reserve,
            reservation_id,
            idempotency_key,
            &call,
            intent_digest,
        )?;
        lease.control_revision = reserve.control_revision;

        let call_digest = control_digest_serialized(
            "Proof-Operator-Dispatch-Call-v1",
            &call.intent,
        )
        .map_err(|error| {
            OperatorRuntimeError::contract(OperatorRuntimeStage::BeginDispatch, error.to_string())
        })?;
        let replay_claim_token = call
            .replay
            .as_ref()
            .map(|_| self.environment.new_uuid_v7())
            .transpose()?;
        let mut dispatch =
            DispatchTokenCustody::new(self.random_token(OperatorRandomPurpose::DispatchToken)?);
        let begin = {
            let authority = lease
                .custody
                .authority(lease.control_revision)
                .map_err(|error| {
                    OperatorRuntimeError::contract(
                        OperatorRuntimeStage::BeginDispatch,
                        error.to_string(),
                    )
                })?;
            let request = dispatch
                .begin_request(
                    authority,
                    reservation_id,
                    call.intent.clone(),
                    intent_digest,
                    call.replay.clone(),
                    replay_claim_token,
                    call_digest,
                )
                .map_err(|error| {
                    OperatorRuntimeError::contract(
                        OperatorRuntimeStage::BeginDispatch,
                        error.to_string(),
                    )
                })?;
            self.store.begin_dispatch(request)
        };
        let begin = match begin {
            Ok(result) => result,
            Err(error) => {
                lease.lose_authority_on(error);
                return Err(OperatorRuntimeError::store(
                    OperatorRuntimeStage::BeginDispatch,
                    error,
                ));
            }
        };
        begin.validate().map_err(|_| {
            OperatorRuntimeError::contract(
                OperatorRuntimeStage::BeginDispatch,
                "store returned an invalid dispatch result",
            )
        })?;
        // A valid begin result is the store's new authoritative revision even
        // when no dispatch is authorized (including a replay completion that
        // later fails runtime-side binding validation).
        lease.control_revision = begin.control_revision;
        if begin.outcome == DispatchOutcome::ExactReplay {
            let completion = begin.replay_completion.ok_or_else(|| {
                OperatorRuntimeError::contract(
                    OperatorRuntimeStage::BeginDispatch,
                    "exact replay omitted completion",
                )
            })?;
            self.verify_completion(
                call.replay.as_ref().ok_or_else(|| {
                    OperatorRuntimeError::contract(
                        OperatorRuntimeStage::BeginDispatch,
                        "unexpected replay completion",
                    )
                })?,
                &completion,
            )?;
            return Ok(GovernedRuntimeOutcome::ExactReplay(completion));
        }
        if begin.outcome != DispatchOutcome::DispatchAuthorized {
            // Every non-authorized begin outcome has already atomically
            // released or rejected the reservation in storage. Retain the
            // store's resulting control revision before returning so a later
            // fenced attempt never reuses the pre-begin revision.
            return Err(OperatorRuntimeError::ReplayRejected(begin.outcome));
        }
        dispatch
            .bind_permit(&begin, self.environment.as_ref())
            .map_err(|error| {
                OperatorRuntimeError::contract(
                    OperatorRuntimeStage::BeginDispatch,
                    error.to_string(),
                )
            })?;
        let permit = begin
            .permit
            .as_ref()
            .expect("validated authorized result")
            .clone();
        let replay_claim = call.replay.as_ref().map(|binding| ExecutionReplayClaim {
            key: ExecutionReplayKey {
                operation: binding.operation.clone(),
                version: binding.version.clone(),
                idempotency_key: binding.idempotency_key,
            },
            input_digest: binding.input_digest,
            claim_token: replay_claim_token.expect("replay begin has a claim token"),
            claimed_by: binding.claimed_by,
            claimed_at: permit.authorized_at,
        });
        let prepared = {
            let authorization = dispatch.authorization(&lease.live).map_err(|error| {
                OperatorRuntimeError::contract(
                    OperatorRuntimeStage::ExecuteBoundary,
                    error.to_string(),
                )
            })?;
            self.engine.execute_evidenced_unpersisted(
                &call.intent.operation,
                &call.intent.version,
                &call.input,
                &call.context,
                proof_kernel::GovernedExecutionPlan {
                    authorization,
                    intent: call.intent.clone(),
                    run_before: call.run_before.clone(),
                    step_before: call.step_before.clone(),
                    checkpoint_tail: Some(call.checkpoint.clone()),
                    replay_claim,
                },
            )
        };
        let prepared = match prepared {
            Ok(prepared) => prepared,
            Err(error) => {
                let settlement = self.settle_failure(
                    lease,
                    dispatch,
                    &permit,
                    governed_runtime_failure_code(&error),
                )?;
                return Err(OperatorRuntimeError::ExecutionSettled { error, settlement });
            }
        };
        let binding = match PreparedExecutionBinding::from_prepared(
            &prepared,
            call.replay.as_ref().map(|value| value.binding_digest),
        ) {
            Ok(binding) => binding,
            Err(error) => {
                let settlement = self.settle_failure(
                    lease,
                    dispatch,
                    &permit,
                    governed_runtime_failure_code(&error),
                )?;
                return Err(OperatorRuntimeError::ExecutionSettled { error, settlement });
            }
        };
        let request = {
            let authority = lease
                .custody
                .authority(lease.control_revision)
                .map_err(|error| {
                    OperatorRuntimeError::contract(
                        OperatorRuntimeStage::CommitResult,
                        error.to_string(),
                    )
                })?;
            dispatch
                .into_commit_request(authority, binding)
                .map_err(|error| {
                    OperatorRuntimeError::contract(
                        OperatorRuntimeStage::CommitResult,
                        error.to_string(),
                    )
                })?
        };
        let result = match self.store.commit_runtime_barrier(request, prepared) {
            Ok(result) => result,
            Err(error) => {
                lease.lose_authority_on(error);
                return Err(OperatorRuntimeError::store(
                    OperatorRuntimeStage::CommitResult,
                    error,
                ));
            }
        };
        result.validate().map_err(|_| {
            OperatorRuntimeError::contract(
                OperatorRuntimeStage::CommitResult,
                "store returned an invalid runtime commit",
            )
        })?;
        lease.control_revision = result.control_revision;
        Ok(GovernedRuntimeOutcome::Committed(result))
    }

    /// Explicitly releases a proven pre-dispatch reservation. It never acts on
    /// a dispatching reservation and therefore cannot mask an ambiguous effect.
    pub fn release_pre_dispatch(
        &self,
        lease: &mut OperatorLease,
        reservation_id: Uuid,
    ) -> Result<BudgetSettlementResult, OperatorRuntimeError> {
        let authority = lease
            .custody
            .authority(lease.control_revision)
            .map_err(|error| {
                OperatorRuntimeError::contract(
                    OperatorRuntimeStage::SettleBudget,
                    error.to_string(),
                )
            })?;
        let result = match self
            .store
            .settle_budget_reservation(BudgetSettlementRequest {
                schema: "proof.operator.budget-settlement-request/v1".into(),
                authority,
                reservation_id,
                disposition: BudgetSettlementDisposition::ReleasePreDispatch,
            }) {
            Ok(result) => result,
            Err(error) => {
                lease.lose_authority_on(error);
                return Err(OperatorRuntimeError::store(
                    OperatorRuntimeStage::SettleBudget,
                    error,
                ));
            }
        };
        result.validate().map_err(|_| {
            OperatorRuntimeError::contract(
                OperatorRuntimeStage::SettleBudget,
                "store returned an invalid budget settlement",
            )
        })?;
        lease.control_revision = result.control_revision;
        Ok(result)
    }

    fn random_token(
        &self,
        purpose: OperatorRandomPurpose,
    ) -> Result<[u8; 32], OperatorRuntimeError> {
        let mut token = [0_u8; 32];
        self.environment.fill_random(purpose, &mut token)?;
        Ok(token)
    }

    fn validate_call(
        &self,
        lease: &OperatorLease,
        call: &GovernedRuntimeCall,
    ) -> Result<(), OperatorRuntimeError> {
        call.intent.validate().map_err(|_| {
            OperatorRuntimeError::contract(
                OperatorRuntimeStage::ReserveBudget,
                "dispatch intent is invalid",
            )
        })?;
        let canonical_input = canonicalize(&call.input).map_err(|error| {
            OperatorRuntimeError::contract(OperatorRuntimeStage::ReserveBudget, error.to_string())
        })?;
        let input_digest = digest(ArtifactKind::OperationInput, &canonical_input);
        let argument_digest = control_digest(
            "Proof-Operator-Dispatch-Argument-v1",
            canonical_input.as_bytes(),
        );
        if call.run_before.id != lease.lease.run_id
            || call.step_before.run_id != call.run_before.id
            || call.step_before.operation != call.intent.operation
            || call.step_before.version != call.intent.version
            || call.step_before.input_digest != input_digest
            || call.context.actor != call.run_before.actor
            || call.intent.argument_digest != argument_digest
        {
            return Err(OperatorRuntimeError::contract(
                OperatorRuntimeStage::ReserveBudget,
                "governed call does not match its run, step, input, or lease",
            ));
        }
        if let Some(binding) = call.replay.as_ref() {
            if call.intent.kind != proof_kernel::BoundaryKind::Tool
                || binding.validate().is_err()
                || binding.workspace_id != lease.lease.workspace_id
                || binding.run_id != call.run_before.id
                || binding.step_id != call.step_before.id
                || binding.checkpoint_id != call.checkpoint.checkpoint_id
                || binding.checkpoint_sequence != u64::from(call.checkpoint.sequence)
                || binding.checkpoint_digest != call.checkpoint.state_digest
                || binding.operation != call.intent.operation
                || binding.version != call.intent.version
                || binding.input_digest != input_digest
                || binding.claimed_by != call.context.actor
            {
                return Err(OperatorRuntimeError::contract(
                    OperatorRuntimeStage::ReplayLookup,
                    "replay binding does not match the governed call",
                ));
            }
        } else if call.intent.kind == proof_kernel::BoundaryKind::Tool
            && call
                .recovery
                .as_ref()
                .is_some_and(|value| value.replay.is_some())
        {
            return Err(OperatorRuntimeError::contract(
                OperatorRuntimeStage::ReserveBudget,
                "recovery replay binding is missing",
            ));
        }
        Ok(())
    }

    fn accept_renewal(
        &self,
        lease: &mut OperatorLease,
        result: LeaseMutationResult,
    ) -> Result<(), OperatorRuntimeError> {
        if result.validate().is_err()
            || result.outcome != LeaseMutationOutcome::Renewed
            || result.lease.workspace_id != lease.lease.workspace_id
            || result.lease.run_id != lease.lease.run_id
            || result.lease.lease_id != lease.lease.lease_id
            || result.lease.owner_instance_id != lease.lease.owner_instance_id
            || result.lease.process_epoch_id != lease.lease.process_epoch_id
            || result.lease.fence_epoch != lease.lease.fence_epoch
        {
            lease.invalidate_local_authority();
            return Err(OperatorRuntimeError::contract(
                OperatorRuntimeStage::RenewLease,
                "store returned an invalid lease renewal",
            ));
        }
        lease.control_revision = result.control_revision;
        lease.lease = result.lease;
        Ok(())
    }

    #[allow(clippy::too_many_arguments)]
    fn validate_reservation(
        &self,
        lease: &OperatorLease,
        result: &BudgetReserveResult,
        reservation_id: Uuid,
        idempotency_key: Uuid,
        call: &GovernedRuntimeCall,
        intent_digest: proof_kernel::ControlDigest,
    ) -> Result<(), OperatorRuntimeError> {
        let value = &result.reservation;
        if result.validate().is_err()
            || value.reservation_id != reservation_id
            || value.idempotency_key != idempotency_key
            || value.run_id != lease.lease.run_id
            || value.lease_id != lease.lease.lease_id
            || value.fence_epoch != lease.lease.fence_epoch
            || value.intent != call.intent
            || value.intent_digest != intent_digest
            || value.replay != call.replay
            || value.recovery != call.recovery
        {
            return Err(OperatorRuntimeError::contract(
                OperatorRuntimeStage::ReserveBudget,
                "store returned an invalid budget reservation",
            ));
        }
        Ok(())
    }

    fn lookup_replay(
        &self,
        binding: &ReplayClaimBinding,
    ) -> Result<Option<ReplayCompletionBinding>, OperatorRuntimeError> {
        let result = self
            .store
            .load_completed_replay(ReplayLookupRequest {
                schema: ReplayLookupRequest::SCHEMA.into(),
                binding: binding.clone(),
            })
            .map_err(|error| {
                OperatorRuntimeError::store(OperatorRuntimeStage::ReplayLookup, error)
            })?;
        self.accept_replay_lookup(binding, result)
    }

    fn accept_replay_lookup(
        &self,
        binding: &ReplayClaimBinding,
        result: ReplayLookupResult,
    ) -> Result<Option<ReplayCompletionBinding>, OperatorRuntimeError> {
        result.validate().map_err(|_| {
            OperatorRuntimeError::contract(
                OperatorRuntimeStage::ReplayLookup,
                "store returned an invalid replay lookup",
            )
        })?;
        match result.outcome {
            ReplayLookupOutcome::NotFound => Ok(None),
            ReplayLookupOutcome::Completed => {
                let completion = result.completion.ok_or_else(|| {
                    OperatorRuntimeError::contract(
                        OperatorRuntimeStage::ReplayLookup,
                        "completed replay omitted completion",
                    )
                })?;
                self.verify_completion(binding, &completion)?;
                Ok(Some(completion))
            }
        }
    }

    fn verify_completion(
        &self,
        binding: &ReplayClaimBinding,
        completion: &ReplayCompletionBinding,
    ) -> Result<(), OperatorRuntimeError> {
        if completion.validate().is_err()
            || completion.replay_binding_digest != binding.binding_digest
            || completion.workspace_id != binding.workspace_id
            || completion.run_id != binding.run_id
            || completion.step_id != binding.step_id
            || completion.checkpoint_id != binding.checkpoint_id
            || completion.checkpoint_sequence != binding.checkpoint_sequence
            || completion.checkpoint_digest != binding.checkpoint_digest
            || completion.input_digest != binding.input_digest
            || completion.proof.actor_id != binding.claimed_by.as_uuid()
            || completion.proof.operation != binding.operation
            || completion.proof.version != binding.version
        {
            return Err(OperatorRuntimeError::contract(
                OperatorRuntimeStage::ReplayLookup,
                "completed replay does not match the governed call",
            ));
        }
        Ok(())
    }

    fn settle_failure(
        &self,
        lease: &mut OperatorLease,
        custody: DispatchTokenCustody,
        permit: &proof_kernel::DispatchPermit,
        failure_code: RuntimeFailureCode,
    ) -> Result<RuntimeFailureResult, OperatorRuntimeError> {
        let failure = RuntimeFailureBody {
            schema: "proof.operator.runtime-failure-body/v1".into(),
            reservation_id: permit.reservation_id,
            permit_id: permit.permit_id,
            classification: RuntimeFailureClassification::AmbiguousForfeitRequired,
            failure_code,
            intent_digest: permit.intent_digest,
            call_digest: permit.call_digest,
        };
        let error_digest = control_digest_serialized("Proof-Operator-Runtime-Failure-v1", &failure)
            .map_err(|error| {
                OperatorRuntimeError::contract(
                    OperatorRuntimeStage::SettleFailure,
                    error.to_string(),
                )
            })?;
        let request = {
            let authority = lease
                .custody
                .authority(lease.control_revision)
                .map_err(|error| {
                    OperatorRuntimeError::contract(
                        OperatorRuntimeStage::SettleFailure,
                        error.to_string(),
                    )
                })?;
            custody
                .into_failure_request(authority, failure, error_digest)
                .map_err(|error| {
                    OperatorRuntimeError::contract(
                        OperatorRuntimeStage::SettleFailure,
                        error.to_string(),
                    )
                })?
        };
        let result = match self.store.settle_runtime_failure(request) {
            Ok(result) => result,
            Err(error) => {
                lease.lose_authority_on(error);
                return Err(OperatorRuntimeError::store(
                    OperatorRuntimeStage::SettleFailure,
                    error,
                ));
            }
        };
        result.validate().map_err(|_| {
            OperatorRuntimeError::contract(
                OperatorRuntimeStage::SettleFailure,
                "store returned an invalid runtime failure settlement",
            )
        })?;
        lease.control_revision = result.control_revision;
        Ok(result)
    }
}

